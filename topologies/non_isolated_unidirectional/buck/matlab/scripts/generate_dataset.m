% Generate fixed-load Buck DCM trajectories for hybrid_event_matlab_v3.
% Define split_name before running this script; the default split is train.

script_dir = fileparts(mfilename("fullpath"));
project_root = fileparts(fileparts(script_dir));
model_path = fullfile(script_dir, "buck_ideal_hybrid.slx");
config_path = fullfile(project_root, "configs", ...
    "hybrid_event_matlab_v3", "project.json");

if ~isfile(model_path)
    error("BuckNeuralODE:MissingModel", ...
        "找不到 Simulink 模型：%s", model_path);
end
if ~isfile(config_path)
    error("BuckNeuralODE:MissingConfig", ...
        "找不到项目配置：%s", config_path);
end

run(fullfile(script_dir, "initialize_buck_model.m"));
addpath(script_dir);

if abs(D - 0.5) > 1e-12 || samples_per_cycle ~= 100
    error("BuckNeuralODE:InvalidKnownPWMGrid", ...
        "hybrid_event_matlab_v3 要求 D=0.5 且每周期 100 个采样区间。");
end

if ~exist("split_name", "var")
    selected_split_name = "train";
else
    selected_split_name = string(split_name);
end
clear split_name;
selected_split_name = char(selected_split_name);

project_config = jsondecode(fileread(config_path));
if string(project_config.dataset.schema_version) ~= schema_version
    error("BuckNeuralODE:SchemaMismatch", ...
        "配置 schema 与初始化脚本不一致。");
end
if ~isfield(project_config.dataset.splits, selected_split_name)
    error("BuckNeuralODE:UnknownSplit", ...
        "project.json 中不存在数据划分：%s", selected_split_name);
end

split_config = project_config.dataset.splits.(selected_split_name);
matlab_config = project_config.matlab;
solver_settings = struct( ...
    "solver", string(matlab_config.solver), ...
    "relative_tolerance", matlab_config.relative_tolerance, ...
    "absolute_tolerance", string(matlab_config.absolute_tolerance), ...
    "auto_scale_abs_tol", matlab_config.auto_scale_abs_tol, ...
    "max_step_s", matlab_config.max_step_s, ...
    "zero_crossing_algorithm", ...
        string(matlab_config.zero_crossing_algorithm), ...
    "logging_decimation", matlab_config.logging_decimation);
diode_parameters = matlab_config.diode;
mosfet_parameters = matlab_config.mosfet;

if isempty(split_config.data_seed)
    error("BuckNeuralODE:MissingDataSeed", ...
        "数据划分 %s 未配置 data_seed。", selected_split_name);
end

input_voltages_v = reshape(split_config.voltages_v, 1, []);
trajectories_per_voltage = split_config.trajectories_per_voltage;
num_cycles = split_config.cycles;
random_seed = split_config.data_seed;
current_factor_range = reshape( ...
    project_config.dataset.initial_current_factor, 1, []);
voltage_factor_range = reshape( ...
    project_config.dataset.initial_voltage_factor, 1, []);
maximum_attempts_per_voltage = ...
    project_config.dataset.candidate_multiplier * trajectories_per_voltage;
event_config = project_config.dataset.event_detection;

output_dir = fullfile(project_root, "data", "raw", ...
    "hybrid_event_matlab_v3", selected_split_name);
if ~isfolder(output_dir)
    mkdir(output_dir);
end

rng(random_seed, "twister");
[~, model_name] = fileparts(model_path);
generated_files = strings(0, 1);
accepted_index = 0;

for voltage_index = 1:numel(input_voltages_v)
    vs = input_voltages_v(voltage_index);
    accepted_for_voltage = 0;
    attempt_index = 0;
    nominal_iL = D * vs / R;
    nominal_vC = D * vs;
    candidate_factors = latin_hypercube_2d( ...
        maximum_attempts_per_voltage, ...
        current_factor_range, voltage_factor_range);

    while accepted_for_voltage < trajectories_per_voltage && ...
            attempt_index < maximum_attempts_per_voltage
        attempt_index = attempt_index + 1;
        current_factor = candidate_factors(attempt_index, 1);
        voltage_factor = candidate_factors(attempt_index, 2);
        iL0 = nominal_iL * current_factor;
        vC0 = nominal_vC * voltage_factor;

        in = Simulink.SimulationInput(model_name);
        in = in.setVariable("L", L);
        in = in.setVariable("C", C);
        in = in.setVariable("R", R);
        in = in.setVariable("fs", fs);
        in = in.setVariable("D", D);
        in = in.setVariable("Ts", Ts);
        in = in.setVariable("dt", dt);
        in = in.setVariable("vs", vs);
        in = in.setVariable("iL0", iL0);
        in = in.setVariable("vC0", vC0);
        in = in.setModelParameter( ...
            "StopTime", num2str(num_cycles * Ts, 17));
        in = in.setModelParameter("ReturnWorkspaceOutputs", "on");

        try
            sim_out = sim(in);
        catch exception
            if is_singular_topology_error(exception)
                singular_exception = MException( ...
                    "BuckNeuralODE:SingularTopology", ...
                    "禁用 snubber 的正式拓扑发生奇异：%s", ...
                    exception.message);
                singular_exception = addCause(singular_exception, exception);
                throw(singular_exception);
            end
            rethrow(exception);
        end

        trajectory_id = sprintf( ...
            "%s_%06d", selected_split_name, accepted_index + 1);
        file_path = trajectory_file_path(output_dir, trajectory_id);
        metadata = build_metadata( ...
            trajectory_id, selected_split_name, random_seed, vs, ...
            iL0, vC0, current_factor, voltage_factor, num_cycles, ...
            L, C, R, fs, D, Ts, dt, samples_per_cycle, ...
            solver_settings, diode_parameters, mosfet_parameters, ...
            event_config);

        try
            export_trajectory(sim_out, file_path, metadata);
        catch exception
            if strcmp(exception.identifier, "BuckNeuralODE:DCMViolation")
                fprintf("拒绝 DCM 候选：vs=%.3g V, iL0=%.6g A, vC0=%.6g V, %s\n", ...
                    vs, iL0, vC0, exception.message);
                continue;
            end
            rethrow(exception);
        end

        accepted_for_voltage = accepted_for_voltage + 1;
        accepted_index = accepted_index + 1;
        generated_files(end + 1, 1) = file_path; %#ok<SAGROW>
        fprintf("已保存 %s\n", file_path);
    end

    if accepted_for_voltage < trajectories_per_voltage
        error("BuckNeuralODE:InsufficientDCMTrajectories", ...
            "输入电压 %.3g V 的 %d 个 LHS 候选不足以生成 %d 条合格 DCM 轨迹。", ...
            vs, maximum_attempts_per_voltage, trajectories_per_voltage);
    end
end

expected_count = numel(input_voltages_v) * trajectories_per_voltage;
if numel(generated_files) ~= expected_count
    error("BuckNeuralODE:GeneratedCountMismatch", ...
        "实际保存 %d 条轨迹，配置要求 %d 条。", ...
        numel(generated_files), expected_count);
end
fprintf("数据生成完成，split=%s，共保存 %d 条轨迹。\n", ...
    selected_split_name, numel(generated_files));
clear selected_split_name;


function metadata = build_metadata( ...
        trajectory_id, split_name, random_seed, input_voltage, ...
        initial_current, initial_voltage, current_factor, voltage_factor, ...
        num_cycles, L, C, R, fs, D, Ts, dt, samples_per_cycle, ...
        solver_settings, diode_parameters, mosfet_parameters, event_config)
%BUILD_METADATA Build the complete per-trajectory MATLAB audit record.

    metadata = struct( ...
        "trajectory_id", trajectory_id, ...
        "split", split_name, ...
        "schema_version", "hybrid_event_matlab_v3", ...
        "random_seed", random_seed, ...
        "matlab_release", version("-release"), ...
        "input_voltage_v", input_voltage, ...
        "load_resistance_ohm", R, ...
        "initial_current_a", initial_current, ...
        "initial_voltage_v", initial_voltage, ...
        "current_factor", current_factor, ...
        "voltage_factor", voltage_factor, ...
        "num_cycles", num_cycles, ...
        "L", L, "C", C, "R", R, "fs", fs, "D", D, ...
        "Ts", Ts, "dt", dt, ...
        "samples_per_cycle", samples_per_cycle, ...
        "pwm_starts_on", true, ...
        "solver", solver_settings.solver, ...
        "solver_relative_tolerance", solver_settings.relative_tolerance, ...
        "solver_absolute_tolerance", solver_settings.absolute_tolerance, ...
        "solver_auto_scale_abs_tol", solver_settings.auto_scale_abs_tol, ...
        "solver_max_step_s", solver_settings.max_step_s, ...
        "zero_crossing_algorithm", ...
            solver_settings.zero_crossing_algorithm, ...
        "logging_decimation", solver_settings.logging_decimation, ...
        "device_library", "Simscape Electrical", ...
        "diode_model_type", string(diode_parameters.model_type), ...
        "diode_Ron_ohm", diode_parameters.Ron_ohm, ...
        "diode_Vf_v", diode_parameters.Vf_v, ...
        "diode_Goff_siemens", diode_parameters.Goff_siemens, ...
        "diode_junction_capacitance_pf", ...
            diode_parameters.junction_capacitance_pf, ...
        "diode_reverse_recovery", ...
            string(diode_parameters.reverse_recovery), ...
        "mosfet_model_type", string(mosfet_parameters.model_type), ...
        "mosfet_Rds_on_ohm", mosfet_parameters.Rds_on_ohm, ...
        "mosfet_Goff_siemens", mosfet_parameters.Goff_siemens, ...
        "mosfet_threshold_voltage_v", ...
            mosfet_parameters.threshold_voltage_v, ...
        "mosfet_body_diode_mode", ...
            string(mosfet_parameters.body_diode_mode), ...
        "diode_on_threshold_a", event_config.diode_on_threshold_a, ...
        "diode_off_threshold_a", event_config.diode_off_threshold_a, ...
        "event_current_abs_tol_a", event_config.event_current_abs_tol_a, ...
        "idle_current_abs_tol_a", event_config.idle_current_abs_tol_a, ...
        "negative_current_abs_tol_a", ...
            event_config.negative_current_abs_tol_a, ...
        "idle_diode_current_abs_tol_a", ...
            event_config.idle_diode_current_abs_tol_a, ...
        "event_guard_time_s", event_config.event_guard_time_s, ...
        "dcm_margin_tau", event_config.dcm_margin_tau, ...
        "gate_edge_time_abs_tol_s", ...
            event_config.gate_edge_time_abs_tol_s);
end


function tf = is_singular_topology_error(exception)
%IS_SINGULAR_TOPOLOGY_ERROR Identify solver messages that require hard stop.

    messages = string(exception.message);
    for index = 1:numel(exception.cause)
        messages(end + 1, 1) = string(exception.cause{index}.message); %#ok<AGROW>
    end
    lowered = lower(messages);
    tf = any(contains(lowered, "singular")) || ...
        any(contains(lowered, "ill-conditioned")) || ...
        any(contains(lowered, "ill conditioned")) || ...
        any(contains(lowered, "topology"));
end
